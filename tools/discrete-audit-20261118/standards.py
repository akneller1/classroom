def code(skill):
    unit, n = skill.rsplit('-skill-', 1)
    return f'DM.{STRAND[unit]}.{int(n)}'


B = load()
for _, q in items(B):
    q['standards'] = [code(q['skillId'])] + EXTRA.get(q['skillId'], [])
save(B)

# Descriptions in standards.js, generated between markers.
p = os.path.join(ROOT, 'worksheet-generator/menu/standards.js')
s = open(p, encoding='utf-8').read()
lines = ['    /* Discrete Math skill-level strands (Discrete Math audit #7, 2026-11-18; generated by tools/discrete-audit-20261118/standards.py). */']
for sk in sorted(notes.N, key=lambda k: (list(STRAND).index(k.rsplit('-skill-', 1)[0]), k)):
    obj = notes.N[sk]['obj']
    lines.append(f'    {json.dumps(code(sk))}: {json.dumps(obj[0].upper() + obj[1:] + ".", ensure_ascii=False)},')
lines.append("    'DM.LP': 'Model and solve two-variable linear programming problems.',")
block = '    /* BEGIN DM SKILLS */\n' + '\n'.join(lines) + '\n    /* END DM SKILLS */\n'
if '/* BEGIN DM SKILLS */' in s:
    s = re.sub(r'    /\* BEGIN DM SKILLS \*/\n.*?    /\* END DM SKILLS \*/\n', lambda m: block, s, flags=re.S)
else:
    anchor = "    'DM.LANG': 'Communicate mathematical reasoning with precise language and notation.',\n"
    assert anchor in s
    s = s.replace(anchor, anchor + block)
open(p, 'w', encoding='utf-8').write(s)
print('retagged; codes', len(notes.N))
