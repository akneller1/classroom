"""Discrete Math audit #7 (2026-11-18): skill-level standards.
Every skill gets its own Discrete Mathematics strand code (DM.<STRAND>.<n>, described in worksheet-generator/menu/standards.js
from the skill's teaching-note objective), plus the Common Core content standards it genuinely practices and a practice
standard only where the skill is about modeling (MP.4) or proof and argument (MP.3).
Run after notes.py; then node scripts/build_standards_map.cjs."""
