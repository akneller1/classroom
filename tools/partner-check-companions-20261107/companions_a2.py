from fractions import Fraction as F
import math, cmath

def roots2(a, b, c):
    d = b*b - 4*a*c
    s = cmath.sqrt(d)
    return sorted([(-b + s) / (2*a), (-b - s) / (2*a)], key=lambda z: (z.real, z.imag))
def close(a, b, tol=1e-9): return abs(a - b) < tol
def vertex(a, b, c): h = F(-b, 2*a); return (h, a*h*h + b*h + c)

