/* Daily Lesson Planner: when the course is Geometry, definitions and key ideas come from MKPLAN_GEOMETRY_NOTES
   (notes-data-geometry.js, generated by scripts/build_geometry_planner.py) so Geometry words never pick up an
   Algebra 1 meaning. Lookup for a word: '<word>|u<unit>' then '<word>'. A teacher's saved edit still wins.
   Load after notes-content.js and notes-data-geometry.js. */
(function (G) {
  'use strict';
  var N = G.MKPLAN_GEOMETRY_NOTES, P = G.MKPLAN;
  if (G.MKPLAN_COURSE !== 'geometry' || !N || !P || !P.define) return;
  var baseDefine = P.define;
  P.GLOSSARY = N.glossary; P.KEY_IDEAS = N.ideas;
  P.define = function (term, day) {
    var e = day && day.lesson_id && P.noteEdits[day.lesson_id];
    if (e && Array.isArray(e.words)) return baseDefine(term, day);
    var t = String(term || '').trim().toLowerCase(), g = N.glossary, u = day && day.unit ? t + '|u' + day.unit : null;
    if (u && g[u] !== undefined) return g[u];
    return g[t] !== undefined ? g[t] : '';
  };
  P.keyIdea = function (lessonId) { var e = P.noteEdits[lessonId]; return e && typeof e.idea === 'string' ? e.idea : (N.ideas[lessonId] || ''); };
})(typeof window !== 'undefined' ? window : globalThis);
