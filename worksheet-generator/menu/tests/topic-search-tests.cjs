'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm');
const env=require('./load.cjs')(['games/bank.js','menu/render.js']),NS=env.MKMENU;
const app=fs.readFileSync(require('path').join(__dirname,'../app.js'),'utf8');
const code=app.slice(app.indexOf('  // Topic worksheets'),app.indexOf('  /* ---------------- start ---------------- */'));
Object.assign(env,{NS,doc:{},S:null,draft:null,ui:{},snapshot(){},render(){},autosave(){},classGroup(){},console});
vm.runInContext(code+'\nregisterTopicSets();',env);
const group=NS.CATALOG.find(g=>g.course==='Algebra 1');
const mixed=NS.skillSets['topic-algebra-1'];assert(mixed);
const slope=mixed.skills.filter(s=>/slope/i.test(s.name));assert(slope.length);
const pick=(word)=>mixed.skills.find(s=>s.name.toLowerCase().includes(word));
const chosen=[pick('slope'),mixed.skills.find(s=>s.topicSource.unit!==pick('slope').topicSource.unit)];
const cart=chosen.map(sk=>{
 const src=sk.topicSource,c=NS.defaultConfig(src.unit,'worksheet');c.coverage.on=false;c.skills={};c.skills[src.skill]=true;c.versions=1;
 c.sections=[{id:NS.uid('sec'),name:sk.name,note:'Show your work.',points:1,offered:1,required:1,tier:4,adjust:0,skills:[src.skill],qformat:'open'}];
 const state=NS.newAssessment(c),p=state.versions[0].sections[0].items[0];assert(!p.failed);
 return {p,section:c.sections[0],skill:sk.id,tag:sk.tag,format:'open'};
});
env.cart=cart;env.group=group;
vm.runInContext('topicCourse=group;topicCart=cart;topicBuild();',env);
assert.equal(env.S.versions[0].sections.length,2);
assert.equal(NS.checkRules(env.S.config,env.S).errors.length,0);
const restored=NS.deserialize(NS.serialize(env.S));
assert.equal(restored.versions[0].sections.length,2);
for(const sec of restored.versions[0].sections)assert(!sec.items[0].failed);
for(const sk of chosen){const p=NS.generateProblem(mixed.id,sk.id,4,{intOnly:true,level:'cp1'},'topic-test');assert(!p.failed);assert.equal(p.skill,sk.id);}
assert.equal(NS.skillFormatOk(mixed.id,chosen[0].id,'multi',4),NS.skillFormatOk(chosen[0].topicSource.unit,chosen[0].topicSource.skill,'multi',4));
console.log('Topic tests passed: cross-unit selection, original generators, format capability, worksheet build, save/restore.');
const geometry=NS.skillSets['topic-geometry'].skills.find(sk=>NS.skillFormatOk(sk.topicSource.unit,sk.topicSource.skill,'open',6));
const gp=NS.generateProblem(geometry.topicSource.unit,geometry.topicSource.skill,6,{intOnly:false,level:'honors'},'cross-class');
assert(!gp.failed);
env.extra={p:gp,section:{qformat:'open',note:'Show your work.',points:1,offered:1,required:1},skill:geometry.id,tag:geometry.tag,format:'open',level:'honors'};
vm.runInContext("topicCourse='all';topicLevel='all';topicCart=cart.concat([extra]);topicBuild();",env);
assert.equal(env.S.config.unitId,'topic-all');
assert.equal(env.S.versions[0].sections.length,3);
assert.equal(NS.sectionC(env.S.config,2),6);
assert.equal(NS.deserialize(NS.serialize(env.S)).versions[0].sections[2].items[0].c,6);
assert.equal(NS.checkRules(env.S.config,env.S).errors.length,0);
console.log('All-classes worksheet preserves source classes and mixed difficulty through save/restore.');
const slopeSrc=chosen[0].topicSource;
env.batchItem=Object.assign({},cart[0],{unit:slopeSrc.unit,level:'cp1'});
vm.runInContext('var repeated=topicQuestionBatch(batchItem,5,[]);',env);
assert.equal(env.repeated.length,5);
assert.equal(new Set(env.repeated.map(env.topicQuestionKey)).size,5);
assert.equal(env.topicQuestionKey(env.repeated[0]),env.topicQuestionKey(env.batchItem));
for(const x of env.repeated){assert.equal(x.p.skill,slopeSrc.skill);assert.equal(x.p.c,cart[0].p.c);assert(!x.p.failed);}
env.existing=env.repeated;
vm.runInContext('var anotherBatch=topicQuestionBatch(batchItem,3,existing);',env);
assert.equal(env.anotherBatch.length,3);
assert.equal(new Set(env.repeated.concat(env.anotherBatch).map(env.topicQuestionKey)).size,8);
vm.runInContext("topicCart=repeated;topicBuild();",env);
assert.equal(env.S.versions[0].sections.length,5);
assert.equal(NS.deserialize(NS.serialize(env.S)).versions[0].sections.length,5);
console.log('Skill quantity tests passed: requested counts, distinct questions, existing-selection deduplication, difficulty, save/restore.');
const mcConfig=NS.defaultConfig(slopeSrc.unit,'worksheet');mcConfig.level='cp1';mcConfig.coverage.on=false;mcConfig.skills={};mcConfig.skills[slopeSrc.skill]=true;
mcConfig.sections=[Object.assign({},cart[0].section,{tier:1,qformat:'mc'})];
const mcState=NS.newAssessment(mcConfig);
env.mcItem=Object.assign({},env.batchItem,{p:mcState.versions[0].sections[0].items[0],section:mcConfig.sections[0],format:'mc'});
vm.runInContext('var mcBatch=topicQuestionBatch(mcItem,4,[]);',env);
assert.equal(env.mcBatch.length,4);
for(const x of env.mcBatch){assert(x.p.mc);assert.equal(x.p.c,4);assert.equal(x.p.skill,slopeSrc.skill);}
console.log('Multiple-choice quantity retains checked choices and requested difficulty.');
const sTopics=env.topicSuggestionsFor(group,'s'),slTopics=env.topicSuggestionsFor(group,'sl');
assert(sTopics.some(x=>x==='Slope'));
assert(sTopics.some(x=>/systems/i.test(x)));
assert(slTopics.some(x=>x==='Slope'));
assert(!slTopics.some(x=>/systems/i.test(x)));
assert(slTopics.every(x=>sTopics.includes(x)));
assert.equal(env.topicSuggestionsFor(group,'').length,0);
assert.equal(new Set(sTopics.map(x=>x.toLowerCase())).size,sTopics.length);
assert.equal(env.topicSuggestionsFor(NS.CATALOG.find(g=>g.course==='Geometry'),'sl').includes('Slope'),false);
assert(env.topicSuggestionsFor('all','sl').includes('Slope'));
assert(!sTopics.some(x=>/^Unit \d/.test(x)));
console.log('Suggestions passed: s includes slope and systems, sl narrows to slope, class scoping, all classes, deduplication.');
