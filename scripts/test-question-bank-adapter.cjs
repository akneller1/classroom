#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),ctx={window:{}};
for(const file of ['course-catalog.js','question-bank-adapter.js']) vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
const api=ctx.window.MK_QUESTION_BANKS, skill=ctx.window.MK_COURSE_CATALOG.getSkillRecords('math6','ratios-rates-percent-proportions')[0];
assert.ok(skill);
const one={id:'fixture-001',skillId:skill.id,level:'cp2',format:'multiple-choice',prompt:'Fixture question for structure tests only',answer:'A',solutionSteps:['Fixture solution'],options:[{text:'A',correct:true},{text:'B',correct:false}]};
const unit={schemaVersion:1,courseId:'math6',unitId:'ratios-rates-percent-proportions',questions:[one]};
assert.equal(api.validate(unit).ok,true);
assert.equal(api.available('math6',unit.unitId),false);
assert.equal(api.register(unit).ok,true);
assert.equal(api.available('math6',unit.unitId),false,'Unverified bank must remain unavailable');
assert.equal(api.select({courseId:'math6',unitId:unit.unitId}).length,0,'No unverified student questions');
assert.equal(api.select({courseId:'math6',unitId:unit.unitId,includeUnverified:true}).length,1);
assert.equal(api.coverage('math6',unit.unitId)[0].counts.cp2,1);
const original=api.select({courseId:'math6',unitId:unit.unitId,includeUnverified:true});
original[0].prompt='Changed';assert.notEqual(api.select({courseId:'math6',unitId:unit.unitId,includeUnverified:true})[0].prompt,'Changed','Return copies');
assert.equal(api.register(unit).ok,false,'Duplicate unit bank rejected');
const invalid=JSON.parse(JSON.stringify(unit));invalid.questions[0].options[1].correct=true;
assert.equal(api.validate(invalid).ok,false,'Multiple correct options rejected');
const invalidSkill=JSON.parse(JSON.stringify(unit));invalidSkill.questions[0].skillId='nonexistent';
assert.equal(api.validate(invalidSkill).ok,false,'Unknown skills rejected');
const honors={...one,id:'fixture-002',level:'honors',format:'open-response',parts:[{prompt:'A',answer:1},{prompt:'B',answer:2},{prompt:'C',answer:3},{prompt:'D',answer:4}]};
const second={...unit,unitId:'fractions-decimals-operations',questions:[{...honors,skillId:ctx.window.MK_COURSE_CATALOG.getSkillRecords('math6','fractions-decimals-operations')[0].id}]};
assert.equal(api.register(second,{verified:true}).ok,true);
assert.equal(api.available('math6',second.unitId),true);
assert.equal(api.select({courseId:'math6',unitId:second.unitId,level:'cp2'}).length,0);
assert.equal(api.select({courseId:'math6',unitId:second.unitId,level:'honors',formats:['open-response']}).length,1);
console.log('PASS question bank validation, gating, selection, coverage, and immutability');
