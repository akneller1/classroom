#!/usr/bin/env python3
"""Turn worksheet-generator/planner/algebra1_scope_sequence.json (Andrey's 180-day scope & sequence)
into worksheet-generator/planner/scope-algebra1.js (window.MKPLAN_SCOPE) for the Daily Lesson Planner.
The per-day "components" field repeats day_types[day_type] and is dropped. Rerun after editing the JSON."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'worksheet-generator', 'planner')
data = json.load(open(os.path.join(D, 'algebra1_scope_sequence.json'), encoding='utf-8'))
for day in data['days']:
    comp = day.pop('components', None)
    if comp is not None and comp != data['day_types'][day['day_type']]:
        day['components'] = comp          # keep only a day-specific override
with open(os.path.join(D, 'scope-algebra1.js'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by scripts/build_planner_scope.py from algebra1_scope_sequence.json. Do not edit by hand. */\n')
    f.write('window.MKPLAN_SCOPE = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('scope-algebra1.js: %d days, %d units' % (len(data['days']), len(data['units'])))
