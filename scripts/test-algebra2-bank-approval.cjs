'use strict';
// Regression tests: only an unchanged Algebra 2 authored-bank item skips manual approval.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const src = fs.readFileSync(path.join(__dirname, '../worksheet-generator/algebra2-bank-native.js'),'utf8');
const start = src.indexOf('NS.isUneditedAlgebra2BankQuestion=function(p){');
const end = src.indexOf('\nconst makeChoices=', start);
assert(start>=0 && end>start, 'bank provenance guard exists');
const q = {id:'a2-test',skillId:'skill-01',prompt:'What is 1 + 1?',answer:'2',format:'short-answer',solutionSteps:[]};
const raw = new Map([[q.id,q]]);
const NS = {};
const problem = (q,id,c)=>({source:'authored-bank',sourceId:q.id,skill:q.skillId,prompt:q.prompt,parts:[{answer:q.answer,prompt:''}],fig:null,work:null});
const menuSource = p=>JSON.stringify([p.prompt||'',(p.parts||[]).map(x=>[x.prompt||'',x.answer||'']),p.fig||null,p.work||null]);
vm.runInNewContext(src.slice(start,end),{NS,raw,problem,menuSource});
const pristine = problem(q,null,4);
assert.equal(NS.isUneditedAlgebra2BankQuestion(pristine),true,'bank item uses source answer');
assert.equal(NS.isUneditedAlgebra2BankQuestion({...pristine,edited:true}),false,'edited bank item needs manual check');
assert.equal(NS.isUneditedAlgebra2BankQuestion({...pristine,source:'edited'}),false,'teacher-edited item needs manual check');
assert.equal(NS.isUneditedAlgebra2BankQuestion({...pristine,parts:[{answer:'3',prompt:''}]}),false,'altered answer needs manual check');
assert.equal(NS.isUneditedAlgebra2BankQuestion({...pristine,prompt:'Another question'}),false,'altered prompt needs manual check');
assert.equal(NS.isUneditedAlgebra2BankQuestion({...pristine,source:'manual'}),false,'teacher-written item needs manual check');
console.log('Algebra 2 bank provenance approval checks passed.');
