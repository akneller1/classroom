#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage();
 fs.mkdirSync('test-results',{recursive:true});
 try{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.MK_BASE_URL||'http://127.0.0.1:8765';
  await page.goto(base+'/worksheet-generator/bank-printable.html?unit=functions-transformations');
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Ready to generate.'),{timeout:20000});
  assert.equal(await page.locator('#sectionList .section-config').count(),8);
  await page.locator('#sectionList .section-config').first().getByRole('button',{name:'Duplicate'}).click();
  assert.equal(await page.locator('#sectionList .section-config').count(),9);
  await page.locator('#sectionList .section-config').first().getByRole('button',{name:'↓'}).click();
  await page.locator('#sectionList .section-config').first().locator('input[aria-label^="Section"]').fill('Warm-up');
  await page.locator('#count').fill('20');
  await page.locator('#versions').fill('2');
  await page.locator('#build').click();
  await page.locator('#editor').waitFor({state:'visible'});
  assert.equal(await page.locator('#output .sheet:not(.key)').count(),2);
  assert.equal(await page.locator('#output .sheet.key').count(),2);
  assert.ok(await page.locator('#output .section-print h3').count()>=9);
  const first=page.locator('#editItems textarea').first();
  await first.fill('Temporary edited question');
  await page.locator('#resetEdits').click();
  assert.equal(await page.locator('#output .sheet:not(.key) .item').count()>0,true);
  assert.equal(await page.locator('#output .sheet.key .item').count()>0,true);
  await page.locator('#currentVersion').selectOption('1');
  await page.locator('#refreshVersion').click();
  assert.equal(await page.locator('#output .sheet:not(.key)').count(),2);
  await page.goto(base+'/worksheet-generator/bank-printable.html?unit=quadratic-functions-complex-numbers');
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Ready to generate.'));
  await page.locator('#spiralEnabled').check();
  assert.equal(await page.locator('#spiralUnits input:not([disabled])').count()>=2,true);
  const mixed=page.locator('#sectionList .section-config').nth(1);
  await mixed.locator('input[type="number"]').fill('4');
  await page.locator('#count').fill('20');
  await page.locator('#build').click();
  await page.locator('#editor').waitFor({state:'visible'});
  const mixItems=await page.locator('#output .sheet:not(.key)').first().locator('.section-print').nth(1).locator('.item').count();
  assert.ok(mixItems>0,'Spiral Mixed Review should include existing questions');
  const studentSections=page.locator('#output .sheet:not(.key)');
  const teacherSections=page.locator('#output .sheet.key');
  assert.equal(await studentSections.count(),1);
  assert.equal(await teacherSections.count(),1);
  assert.equal(await studentSections.first().locator('.item').count(),await teacherSections.first().locator('.item').count(),'Student and teacher problem counts must match');
  await page.emulateMedia({media:'print'});
  assert.equal(await page.locator('.setup').evaluate(el=>getComputedStyle(el).display),'none');
  assert.equal(await page.locator('#editor').evaluate(el=>getComputedStyle(el).display),'none');
  assert.equal(await studentSections.first().evaluate(el=>getComputedStyle(el).display)!=='none',true);
  assert.equal(await teacherSections.first().evaluate(el=>getComputedStyle(el).display)!=='none',true);
  assert.match(await teacherSections.first().evaluate(el=>getComputedStyle(el).breakBefore),/page|auto/);
  const pdf=await page.pdf({format:'Letter',printBackground:true});
  fs.writeFileSync('test-results/algebra2-print-preview.pdf',pdf);
  assert.ok(pdf.length>1000,'Printed PDF must contain pages');
  await page.emulateMedia({media:'screen'});
  await page.locator('#key').uncheck();
  assert.equal(await page.locator('#output .sheet.key').count(),0,'Teacher keys must be optional');
  await page.locator('#key').check();
  assert.equal(await page.locator('#output .sheet.key').count(),1);
  assert.deepEqual(errors,[]);
  console.log('PASS Algebra 2 generator browser: sections, duplication, ordering, versions, edits, reset, keys');
 }catch(error){
  console.error('Generator browser test failed:',error);
  console.error('Page:',page.url());
  console.error('Status:',await page.locator('#status').textContent().catch(()=>'(missing)'));
  await page.screenshot({path:'test-results/algebra2-failure.png',fullPage:true}).catch(()=>{});
  throw error;
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
